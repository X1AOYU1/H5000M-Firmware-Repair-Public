import assert from 'node:assert/strict';

const events=new EventTarget();
globalThis.window=events;
globalThis.document=Object.assign(new EventTarget(),{hidden:false});
let selected='1',requests=0,active=0,max=0,fail=false;
globalThis.localStorage={getItem:()=>selected};
globalThis.fetch=async()=>{
  requests++;max=Math.max(max,++active);
  await new Promise(r=>setTimeout(r,30));active--;
  return {ok:!fail,redirected:false,json:async()=>({data:{upload:requests,download:requests*10}})};
};
const {subscribeRealtimeSpeed}=await import('../scripts/higoos-realtime-speed.js');
const first=[],second=[];
const stop1=subscribeRealtimeSpeed(v=>first.push(v));
const stop2=subscribeRealtimeSpeed(v=>second.push(v));
await new Promise(r=>setTimeout(r,70));
assert.equal(requests,1,'mounted sidebar and dashboard share first fetch');
assert.deepEqual(first.at(-1),second.at(-1));
assert.equal(first.at(-1).download,10);
await new Promise(r=>setTimeout(r,1030));
assert.equal(requests,2);
selected='5';events.dispatchEvent(new Event('higoos-refresh-change'));
await new Promise(r=>setTimeout(r,70));
const before=requests;
await new Promise(r=>setTimeout(r,1100));
assert.equal(requests,before,'selected slower interval replaces old timer');
document.hidden=true;document.dispatchEvent(new Event('visibilitychange'));
events.dispatchEvent(new Event('higoos-refresh-change'));
await new Promise(r=>setTimeout(r,70));assert.equal(requests,before);
document.hidden=false;document.dispatchEvent(new Event('visibilitychange'));
await new Promise(r=>setTimeout(r,70));assert.equal(requests,before+1);
fail=true;events.dispatchEvent(new Event('higoos-refresh-change'));
await new Promise(r=>setTimeout(r,70));assert.equal(first.at(-1),null,'failed sample never reuses stale speed');
stop1();stop2();
const end=requests;events.dispatchEvent(new Event('higoos-refresh-change'));
await new Promise(r=>setTimeout(r,70));assert.equal(requests,end);
assert.equal(max,1,'sampler never overlaps HTTP requests');
console.log('PASS: shared live speed values, refresh setting, visibility, error and unmount behavior');
